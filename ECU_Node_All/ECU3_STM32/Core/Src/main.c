/**
  * @brief  Function implementing the CANRxHandlerTask thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_CANRxHandler */
void CANRxHandler(void *argument)
{
  /* USER CODE BEGIN 5 */
	  CAN_RxHeaderTypeDef rxHeader;
	  uint8_t rxData[8];

	  /* Tính sẵn ID và byte position cho cửa trái/phải */
	  const uint32_t leftDoorExtId  = DIGITAL_OUTPUT_CMD_ID(LEFT_DOOR_OUTPUT_INDEX / 8U)  & 0x1FFFFFFFUL;
	  const uint8_t  leftDoorByte   = LEFT_DOOR_OUTPUT_INDEX % 8U;    /* = 0 */
	  const uint32_t rightDoorExtId = DIGITAL_OUTPUT_CMD_ID(RIGHT_DOOR_OUTPUT_INDEX / 8U) & 0x1FFFFFFFUL;
	  const uint8_t  rightDoorByte  = RIGHT_DOOR_OUTPUT_INDEX % 8U;   /* = 1 */

	  uint8_t lastLeftCmd  = 0xFF;
	  uint8_t lastRightCmd = 0xFF;
  /* Infinite loop */
  for(;;)
  {
	  while (HAL_CAN_GetRxFifoFillLevel(&hcan, CAN_RX_FIFO0) > 0U)
	      {
	        if (HAL_CAN_GetRxMessage(&hcan, CAN_RX_FIFO0, &rxHeader, rxData) == HAL_OK)
	        {
	          if (rxHeader.IDE == CAN_ID_EXT)
	          {
	            /* --- Cửa trái (TIM2 CH1) --- */
	            if (rxHeader.ExtId == leftDoorExtId)
	            {
	              uint8_t sw = rxData[leftDoorByte] & 0x01U;
	              if (sw != lastLeftCmd)
	              {
	                lastLeftCmd = sw;
	                if (sw) Servo_OpenDoor(TIM_CHANNEL_1);
	                else    Servo_CloseDoor(TIM_CHANNEL_1);
	              }
	            }

	            /* --- Cửa phải (TIM2 CH2) --- */
	            if (rxHeader.ExtId == rightDoorExtId)
	            {
	              uint8_t sw = rxData[rightDoorByte] & 0x01U;
	              if (sw != lastRightCmd)
	              {
	                lastRightCmd = sw;
	                if (sw) Servo_CloseDoor(TIM_CHANNEL_2);
	                else    Servo_OpenDoor(TIM_CHANNEL_2);
	              }
	            }
	          }
	        }
	      }
	      osDelay(5);
  }
  /* USER CODE END 5 */
}

